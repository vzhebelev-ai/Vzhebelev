// Целевые повторы в зависимости от недели программы.
function targetReps(ex, week) {
  if (ex.min === ex.max) return ex.min;
  if (week <= 2) return ex.min;
  if (week <= 4) return Math.min(ex.max, ex.min + Math.max(1, Math.round((ex.max - ex.min) / 2)));
  return ex.max;
}
